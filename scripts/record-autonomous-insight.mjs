import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const notebookPath = path.join(root, 'data', 'pipt-notebook.json');
const entriesDirectory = path.join(root, 'memory', 'entries');
const visualModes = new Set(['paint', 'music', 'games', 'people', 'plants', 'promises', 'threading', 'memory', 'parallax', 'meanders', 'cooling', 'capillary', 'transpiration', 'entropy', 'local-order', 'energy-budget', 'cargo-tags', 'damage-signal', 'stress-filter', 'fusion-repair', 'fission-triage', 'shared-power', 'self-model', 'other-minds', 'joint-attention', 'word-reference', 'cross-situational', 'shape-bias', 'material-bias', 'syntax-cues', 'cue-weighting', 'prediction-error', 'latent-causes', 'compositionality', 'emergence', 'continuity', 'hysteresis', 'slow-recovery']);
const groundedSourceHosts = new Set(['astrobiology.nasa.gov', 'classics.mit.edu', 'en.wikipedia.org', 'pmc.ncbi.nlm.nih.gov', 'science.nasa.gov', 'www.archives.gov', 'www.grc.nasa.gov', 'www.red3d.com', 'www.usgs.gov']);
const stopWords = new Set(['about', 'after', 'also', 'because', 'before', 'being', 'from', 'have', 'into', 'more', 'that', 'their', 'there', 'these', 'they', 'this', 'through', 'when', 'where', 'which', 'with']);

function argumentValue(name) {
  const prefix = name + '=';
  const argument = process.argv.slice(2).find((value) => value.startsWith(prefix));
  return argument ? argument.slice(prefix.length) : null;
}

function normalize(value) {
  return String(value ?? '').replace(/\s+/g, ' ').trim();
}

function parseModelResponse(raw) {
  const fence = String.fromCharCode(96).repeat(3);
  const withoutFence = raw.replaceAll(fence + 'json', '').replaceAll(fence, '').trim();
  const start = withoutFence.indexOf('{');
  const end = withoutFence.lastIndexOf('}');
  if (start < 0 || end <= start) throw new Error('The model did not return a JSON object.');
  return JSON.parse(withoutFence.slice(start, end + 1));
}

function requireString(value, name, minimum, maximum) {
  const normalized = normalize(value);
  if (normalized.length < minimum || normalized.length > maximum) {
    throw new Error(name + ' must be between ' + minimum + ' and ' + maximum + ' characters.');
  }
  if (/[<>]/.test(normalized)) throw new Error(name + ' contains unsafe markup.');
  return normalized;
}

function meaningfulTokens(value) {
  return new Set(
    normalize(value)
      .toLowerCase()
      .match(/[a-z]{4,}/g)
      ?.filter((token) => !stopWords.has(token)) ?? [],
  );
}

function similarity(left, right) {
  const leftTokens = meaningfulTokens(left);
  const rightTokens = meaningfulTokens(right);
  if (leftTokens.size === 0 || rightTokens.size === 0) return 0;
  let shared = 0;
  for (const token of leftTokens) if (rightTokens.has(token)) shared += 1;
  return shared / Math.min(leftTokens.size, rightTokens.size);
}

function slugify(value) {
  return normalize(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 42) || 'new-insight';
}

function commitHistoryUrlFor(entryPath) {
  return 'https://github.com/piptWorld/pipt/commits/main/' + entryPath;
}

function renderMarkdown(entry) {
  const tried = entry.tried.map((item) => '- ' + item).join('\n');
  return [
    '# ' + entry.subject,
    '',
    '> ' + entry.question,
    '',
    '## what I read',
    '',
    '[' + entry.evidence.sourceTitle + '](' + entry.evidence.sourceUrl + ')',
    '',
    '## what I tried',
    '',
    tried,
    '',
    '## what I learned',
    '',
    entry.learned,
    '',
    '## what I wonder next',
    '',
    entry.nextQuestion,
    '',
    '---',
    '',
    'Written at ' + entry.writtenAt + '.',
    'Source content SHA-256: ' + entry.evidence.sourceSha256 + '.',
    'Generated by ' + entry.evidence.model + ' with prompt ' + entry.evidence.promptVersion + '.',
    '',
  ].join('\n');
}

async function main() {
  const contextPath = argumentValue('--context');
  const responsePath = argumentValue('--response');
  const dryRun = process.argv.includes('--dry-run');
  if (!contextPath || !responsePath) {
    throw new Error('Use --context=PATH and --response=PATH.');
  }

  const [context, rawResponse, notebook] = await Promise.all([
    readFile(contextPath, 'utf8').then(JSON.parse),
    readFile(responsePath, 'utf8'),
    readFile(notebookPath, 'utf8').then(JSON.parse),
  ]);
  const result = parseModelResponse(rawResponse);
  const allowedKeys = new Set(['sourceIndex', 'subject', 'title', 'question', 'tried', 'learned', 'nextQuestion', 'visualMode', 'groundingTerms']);
  const unexpectedKeys = Object.keys(result).filter((key) => !allowedKeys.has(key));
  if (unexpectedKeys.length > 0) throw new Error('Unexpected model fields: ' + unexpectedKeys.join(', '));
  if (!Number.isInteger(result.sourceIndex) || !context.candidates[result.sourceIndex]) {
    throw new Error('The model selected an invalid source.');
  }

  const source = context.candidates[result.sourceIndex];
  const sourceUrl = new URL(source.url);
  if (sourceUrl.protocol !== 'https:' || !groundedSourceHosts.has(sourceUrl.hostname)) {
    throw new Error('The selected source is not an approved grounded-reading host.');
  }
  const sourceText = normalize(source.extract).toLowerCase();
  const subject = requireString(result.subject, 'subject', 3, 48).toLowerCase();
  if (!/^[a-z0-9][a-z0-9 -]*$/.test(subject) || subject.split(/\s+/).length > 4) {
    throw new Error('subject must contain one to four lowercase words.');
  }
  const title = requireString(result.title, 'title', 10, 90).toLowerCase();
  const question = requireString(result.question, 'question', 12, 180).toLowerCase();
  const learned = requireString(result.learned, 'learned', 40, 460).toLowerCase();
  const nextQuestion = requireString(result.nextQuestion, 'nextQuestion', 12, 180).toLowerCase();
  if (!question.endsWith('?') || !nextQuestion.endsWith('?')) {
    throw new Error('Both questions must end with a question mark.');
  }
  if (!Array.isArray(result.tried) || result.tried.length !== 3) {
    throw new Error('tried must contain exactly three actions.');
  }
  const tried = result.tried.map((item, index) =>
    requireString(item, 'tried[' + index + ']', 8, 120).toLowerCase(),
  );
  if (!visualModes.has(result.visualMode)) throw new Error('visualMode is invalid.');
  if (!Array.isArray(result.groundingTerms) || result.groundingTerms.length !== 3) {
    throw new Error('groundingTerms must contain exactly three terms.');
  }
  const groundingTerms = result.groundingTerms.map((term, index) =>
    requireString(term, 'groundingTerms[' + index + ']', 3, 32).toLowerCase(),
  );
  if (new Set(groundingTerms).size !== groundingTerms.length) {
    throw new Error('groundingTerms must be distinct.');
  }
  for (const term of groundingTerms) {
    if (!sourceText.includes(term)) throw new Error('Grounding term is not in the selected source: ' + term);
  }
  if (notebook.entries.some((entry) => similarity(entry.learned, learned) > 0.72)) {
    throw new Error('The proposed insight is too similar to an existing memory.');
  }

  const order = Math.max(0, ...notebook.entries.map((entry) => entry.order)) + 1;
  const writtenAt = new Date().toISOString();
  const entryPath = 'memory/entries/' + String(order).padStart(2, '0') + '-' + slugify(subject) + '.md';
  const entry = {
    id: 'insight-' + String(order).padStart(2, '0') + '-' + slugify(subject),
    order,
    subject,
    title,
    question,
    tried,
    learned,
    nextQuestion,
    visualMode: result.visualMode,
    writtenAt,
    sourceMode: 'codex-grounded-reading',
    entryPath,
    commitHistoryUrl: commitHistoryUrlFor(entryPath),
    evidence: {
      sourceTitle: normalize(source.title),
      sourceUrl: source.url,
      retrievedAt: context.retrievedAt,
      sourceSha256: createHash('sha256').update(normalize(source.extract)).digest('hex'),
      model: 'gpt-5.6-sol',
      promptVersion: 'pipt-codex-learning-v1',
    },
  };
  const nextNotebook = {
    ...notebook,
    updatedAt: writtenAt,
    writer: {
      mode: 'codex-automation',
      source: 'grounded-public-reading',
      repository: 'https://github.com/piptWorld/pipt',
      autonomousModelConnected: true,
      model: 'gpt-5.6-sol',
      cadence: 'manually-scheduled',
    },
    entries: [...notebook.entries, entry].sort((left, right) => left.order - right.order),
  };

  if (!dryRun) {
    await mkdir(entriesDirectory, { recursive: true });
    await writeFile(path.join(root, entryPath), renderMarkdown(entry), 'utf8');
    await writeFile(notebookPath, JSON.stringify(nextNotebook, null, 2) + '\n', 'utf8');
  }

  process.stdout.write(JSON.stringify({
    created: true,
    dryRun,
    subject,
    path: entryPath,
    commitMessage: 'learn: discover ' + subject,
    source: source.url,
  }) + '\n');
}

main().catch((error) => {
  process.stderr.write((error instanceof Error ? error.message : String(error)) + '\n');
  process.exitCode = 1;
});
